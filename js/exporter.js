/**
 * EXPORTER MODULE
 * Assembles Sheikah glyphs into a single valid standalone SVG file.
 * Handles SVG download, clipboard copy, and optional PNG export.
 */

import { SHEIKAH_DICT, getSheikahGlyph } from './sheikah-data.js';

export class SheikahExporter {
  constructor(options = {}) {
    this.defaultOptions = {
      glyphSize: 64,
      glyphGap: 12,
      wordGap: 32,
      lineGap: 24,
      padding: 40,
      color: '#00f0ff',
      backgroundColor: 'transparent',
      spaceMode: 'glyph', // 'glyph' or 'blank'
      includeFrame: false,
      title: 'Sheikah Script Translation',
      ...options
    };
  }

  /**
   * Generates a single valid standalone SVG XML string representing the text.
   * @param {string} text 
   * @param {object} customOptions 
   * @returns {string} Fully formed standalone SVG document
   */
  generateSvg(text, customOptions = {}) {
    const opts = { ...this.defaultOptions, ...customOptions };
    const {
      glyphSize,
      glyphGap,
      wordGap,
      lineGap,
      padding,
      color,
      backgroundColor,
      spaceMode,
      includeFrame,
      title
    } = opts;

    if (!text || text.trim() === '') {
      return this.generateEmptySvg(opts);
    }

    const lines = text.split('\n');

    // First pass: compute positions and layout for each glyph
    let maxWidth = 0;
    const positionedGlyphs = [];
    let currentY = padding;

    lines.forEach((line) => {
      let currentX = padding;
      let lineGlyphsCount = 0;

      for (let i = 0; i < line.length; i++) {
        const rawChar = line[i];

        if (rawChar === ' ') {
          if (spaceMode === 'glyph') {
            const spaceData = SHEIKAH_DICT[' '];
            if (spaceData) {
              positionedGlyphs.push({
                char: ' ',
                type: 'glyph',
                data: spaceData,
                x: currentX,
                y: currentY
              });
              currentX += glyphSize + glyphGap;
              lineGlyphsCount++;
            }
          } else {
            currentX += wordGap;
          }
        } else {
          const glyphData = getSheikahGlyph(rawChar);
          if (glyphData) {
            positionedGlyphs.push({
              char: rawChar,
              type: 'glyph',
              data: glyphData,
              x: currentX,
              y: currentY
            });
            currentX += glyphSize + glyphGap;
            lineGlyphsCount++;
          } else {
            // Unknown character fallback box
            positionedGlyphs.push({
              char: rawChar,
              type: 'unknown',
              x: currentX,
              y: currentY
            });
            currentX += glyphSize + glyphGap;
            lineGlyphsCount++;
          }
        }
      }

      // Track width of the widest line
      const lineWidth = lineGlyphsCount > 0 ? (currentX - glyphGap) : currentX;
      if (lineWidth > maxWidth) {
        maxWidth = lineWidth;
      }

      currentY += glyphSize + lineGap;
    });

    const totalWidth = Math.max(maxWidth + padding, 240);
    const totalHeight = Math.max(currentY - lineGap + padding, 140);

    // Build the SVG document
    const svgParts = [];
    svgParts.push(`<?xml version="1.0" encoding="UTF-8"?>`);
    svgParts.push(
      `<svg xmlns="http://www.w3.org/2000/svg" ` +
      `xmlns:xlink="http://www.w3.org/1999/xlink" ` +
      `version="1.1" ` +
      `width="${totalWidth}" ` +
      `height="${totalHeight}" ` +
      `viewBox="0 0 ${totalWidth} ${totalHeight}">`
    );

    // Title & Metadata
    svgParts.push(`  <title>${this.escapeXml(title)}</title>`);
    svgParts.push(`  <desc>Generated by Sheikah Slate Translator - The Legend of Zelda</desc>`);

    // Embedded styling & definitions
    svgParts.push(`  <defs>`);
    svgParts.push(`    <style>`);
    svgParts.push(`      .sheikah-path { fill: ${color}; }`);
    svgParts.push(`      .unknown-box { stroke: ${color}; stroke-width: 2.5; fill: none; opacity: 0.6; }`);
    svgParts.push(`      .unknown-text { font-family: 'Courier New', monospace; font-size: ${Math.round(glyphSize * 0.45)}px; fill: ${color}; font-weight: bold; }`);
    svgParts.push(`      .frame-accent { stroke: ${color}; stroke-width: 2; fill: none; opacity: 0.45; }`);
    svgParts.push(`    </style>`);
    svgParts.push(`  </defs>`);

    // Background rect
    if (backgroundColor && backgroundColor !== 'transparent') {
      svgParts.push(`  <rect width="100%" height="100%" fill="${backgroundColor}" />`);
    }

    // Optional decorative Sheikah frame
    if (includeFrame) {
      svgParts.push(this.generateFrameSvg(totalWidth, totalHeight, color));
    }

    // Glyphs Group
    svgParts.push(`  <g id="sheikah-script-layer">`);

    positionedGlyphs.forEach(item => {
      if (item.type === 'glyph') {
        const g = item.data;
        const scaleX = (glyphSize / g.width).toFixed(4);
        const scaleY = (glyphSize / g.height).toFixed(4);
        const pathsXml = g.paths
          .map(p => `      <path d="${p.d}" class="sheikah-path" fill="${color}" />`)
          .join('\n');

        svgParts.push(
          `    <!-- Character: "${item.char}" -->\n` +
          `    <g transform="translate(${item.x.toFixed(2)}, ${item.y.toFixed(2)}) scale(${scaleX}, ${scaleY})" data-char="${item.char}">\n` +
          `${pathsXml}\n` +
          `    </g>`
        );
      } else if (item.type === 'unknown') {
        const boxSize = glyphSize;
        const half = boxSize / 2;
        const textY = Math.round(half + (glyphSize * 0.16));
        svgParts.push(
          `    <!-- Unknown character: "${item.char}" -->\n` +
          `    <g transform="translate(${item.x.toFixed(2)}, ${item.y.toFixed(2)})">\n` +
          `      <rect x="2" y="2" width="${boxSize - 4}" height="${boxSize - 4}" rx="6" class="unknown-box" stroke-dasharray="4,3"/>\n` +
          `      <text x="${half}" y="${textY}" text-anchor="middle" class="unknown-text">${this.escapeXml(item.char)}</text>\n` +
          `    </g>`
        );
      }
    });

    svgParts.push(`  </g>`);
    svgParts.push(`</svg>`);

    return svgParts.join('\n');
  }

  /**
   * Generates a placeholder SVG when input is empty.
   */
  generateEmptySvg(opts) {
    const { color, backgroundColor } = opts;
    return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="400" height="200" viewBox="0 0 400 200">
  <title>Sheikah Slate - Empty</title>
  ${backgroundColor && backgroundColor !== 'transparent' ? `<rect width="100%" height="100%" fill="${backgroundColor}" />` : ''}
  <circle cx="200" cy="85" r="30" fill="none" stroke="${color}" stroke-width="3" opacity="0.6"/>
  <circle cx="200" cy="85" r="8" fill="${color}"/>
  <text x="200" y="145" text-anchor="middle" font-family="sans-serif" font-size="14" fill="${color}" opacity="0.8">NO TEXT TRANSLATED</text>
</svg>`;
  }

  /**
   * Generates decorative ancient Sheikah frame elements.
   */
  generateFrameSvg(width, height, color) {
    const m = 12; // margin
    const arm = 24; // corner arm length
    return `  <!-- Sheikah Ancient Decorative Frame -->
  <g class="frame-accent">
    <!-- Top Left -->
    <path d="M${m} ${m + arm} L${m} ${m} L${m + arm} ${m}" />
    <!-- Top Right -->
    <path d="M${width - m - arm} ${m} L${width - m} ${m} L${width - m} ${m + arm}" />
    <!-- Bottom Left -->
    <path d="M${m} ${height - m - arm} L${m} ${height - m} L${m + arm} ${height - m}" />
    <!-- Bottom Right -->
    <path d="M${width - m - arm} ${height - m} L${width - m} ${height - m} L${width - m} ${height - m - arm}" />
    <!-- Center Ancient Accent Dots -->
    <circle cx="${width / 2}" cy="${m}" r="2" fill="${color}" opacity="0.7"/>
    <circle cx="${width / 2}" cy="${height - m}" r="2" fill="${color}" opacity="0.7"/>
  </g>`;
  }

  /**
   * Triggers client-side download of the SVG document.
   * @param {string} svgContent 
   * @param {string} filename 
   */
  downloadSvg(svgContent, filename = 'sheikah-slate-translation.svg') {
    const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  }

  /**
   * Copies SVG text to user clipboard.
   * @param {string} svgContent 
   * @returns {Promise<boolean>}
   */
  async copyToClipboard(svgContent) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(svgContent);
      return true;
    }
    // Fallback for older browsers
    const textarea = document.createElement('textarea');
    textarea.value = svgContent;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    const success = document.execCommand('copy');
    document.body.removeChild(textarea);
    return success;
  }

  /**
   * Renders SVG to a PNG image and downloads it.
   * @param {string} svgContent 
   * @param {string} filename 
   * @param {number} scale DPI multiplier
   */
  async downloadPng(svgContent, filename = 'sheikah-slate-translation.png', scale = 2) {
    return new Promise((resolve, reject) => {
      const img = new Image();
      const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
      const url = URL.createObjectURL(blob);

      img.onload = () => {
        const canvas = document.createElement('canvas');
        canvas.width = img.width * scale;
        canvas.height = img.height * scale;
        const ctx = canvas.getContext('2d');
        ctx.scale(scale, scale);
        ctx.drawImage(img, 0, 0);
        URL.revokeObjectURL(url);

        canvas.toBlob((pngBlob) => {
          if (!pngBlob) {
            reject(new Error('PNG conversion failed'));
            return;
          }
          const pngUrl = URL.createObjectURL(pngBlob);
          const link = document.createElement('a');
          link.href = pngUrl;
          link.download = filename;
          document.body.appendChild(link);
          link.click();
          document.body.removeChild(link);
          setTimeout(() => URL.revokeObjectURL(pngUrl), 2000);
          resolve(true);
        }, 'image/png');
      };

      img.onerror = (err) => {
        URL.revokeObjectURL(url);
        reject(err);
      };

      img.src = url;
    });
  }

  /**
   * XML Entity escaping.
   */
  escapeXml(str) {
    if (!str) return '';
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&apos;');
  }
}
